export function normalizeCategoryKey(raw: string): string {
  return raw
    .trim()
    .toLowerCase()
    .normalize('NFD')
    .replace(/\p{M}/gu, '')
    .replace(/&/g, 'and')
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_|_$/g, '');
}

function tryTranslateSlug(slug: string, t: TFunction): string | null {
  if (!CATEGORY_SLUGS.has(slug)) return null;
  const key = `catalog.categories.${slug}`;
  const translated = t(key);
  return translated !== key ? String(translated) : null;
}

function resolveFromKey(key: string): string | null {
  if (!key) return null;
  if (CATEGORY_SLUGS.has(key)) return key;
  const aliased = ALIASES[key];
  if (aliased && CATEGORY_SLUGS.has(aliased)) return aliased;
  return null;
}

function resolveSlug(name: string, slug?: string | null): string | null {
  const fromName = normalizeCategoryKey(name);
  const byName = resolveFromKey(fromName);
  if (byName) return byName;

  if (slug?.trim()) {
    const s = normalizeCategoryKey(slug);
    const byFullSlug = resolveFromKey(s);
    if (byFullSlug) return byFullSlug;

    const parts = s.split('_').filter(Boolean);
    for (let start = 0; start < parts.length; start++) {
      const segment = parts.slice(start).join('_');
      if (GENERIC_SLUG_SEGMENTS.has(segment)) continue;
      const resolved = resolveFromKey(segment);
      if (resolved) return resolved;
    }
  }

  return null;
}

export function translateCategoryLabel(
  input: CategoryLabelSource | string,
  t: TFunction
): string {
  const name = typeof input === 'string' ? input : input.name;
  const slug = typeof input === 'string' ? undefined : input.slug;
  const trimmed = name?.trim() ?? '';
  if (!trimmed && !slug?.trim()) return '';

  const resolved = resolveSlug(trimmed, slug);
  if (resolved) {
    const translated = tryTranslateSlug(resolved, t);
    if (translated) return translated;
  }

  return trimmed || String(slug ?? '').trim();
}
